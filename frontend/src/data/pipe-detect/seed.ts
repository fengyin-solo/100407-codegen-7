import type { DetectReport, DetectRound, ResultCode } from './types'

/** 管道检测报告示例数据：首次打开播种，之后以 localStorage 里的为准。
 * 用构造函数压缩篇幅：r() 造一轮已完成检测，p() 造一条进行中轮次。 */

let idSeq = 0

function r(
  seq: number,
  kind: DetectRound['kind'],
  method: string,
  device: string,
  inspector: string,
  lengthM: number,
  detectDate: string,
  resultCode: ResultCode,
  remark = '',
): DetectRound {
  return { seq, kind, started: true, method, device, inspector, lengthM, detectDate, completedDate: detectDate, resultCode, remark }
}

/** 进行中：已进场开检但尚未出结论。 */
function p(seq: number, method: string, device: string, inspector: string, lengthM: number, detectDate: string, remark = ''): DetectRound {
  return { seq, kind: seq === 1 ? '初检' : '复测', started: true, method, device, inspector, lengthM, detectDate, completedDate: null, resultCode: null, remark }
}

/** 已排期但尚未进场：算「待检测」。 */
function scheduled(seq: number, detectDate: string, remark = ''): DetectRound {
  return { seq, kind: seq === 1 ? '初检' : '复测', started: false, method: '', device: '', inspector: '', lengthM: 0, detectDate, completedDate: null, resultCode: null, remark }
}

function report(
  reportNo: string,
  segment: string,
  material: string,
  diameterMm: number,
  rounds: DetectRound[],
  adoptedSeq = rounds.filter((round) => round.completedDate).length,
  adoptBasis = '',
  pendingRetest = false,
): DetectReport {
  idSeq += 1
  const completed = rounds.filter((round) => round.completedDate)
  const basis =
    adoptBasis ||
    (adoptedSeq > 0 ? `按规范以最近一轮（第${adoptedSeq}轮${rounds[adoptedSeq - 1]?.kind ?? ''}）结论为当前依据` : '检测尚未完成，暂无采用依据')
  return {
    id: idSeq,
    reportNo,
    segment,
    material,
    diameterMm,
    version: completed.length,
    adoptedSeq,
    adoptBasis: basis,
    pendingRetest,
    rounds,
  }
}

